const mongoose = require("mongoose");

const paise = (required = true) => ({
  type: Number,
  required,
  min: 0,
  validate: {
    validator: Number.isSafeInteger,
    message: "Amount must be a non-negative safe integer in paise",
  },
});

const expenseLineSchema = new mongoose.Schema(
  {
    expenseLedgerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "AccountingLedger",
      required: true,
    },
    ledgerCode: { type: String, required: true, trim: true, uppercase: true },
    ledgerName: { type: String, required: true, trim: true },
    description: { type: String, required: true, trim: true, maxlength: 300 },

    // Amount before GST.
    amountPaise: { ...paise(), min: 1 },
    gstRate: { type: Number, enum: [0, 5, 12, 18, 28], default: 0 },
    taxPaise: paise(),
    totalPaise: { ...paise(), min: 1 },
  },
  { _id: false },
);

const expenseSchema = new mongoose.Schema(
  {
    tenantId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Tenant",
      required: true,
      index: true,
    },

    expenseNumber: {
      type: String,
      required: true,
      trim: true,
      uppercase: true,
    },

    // Generated by the frontend once per create attempt (idempotency).
    requestId: {
      type: String,
      required: true,
      trim: true,
      lowercase: true,
    },

    expenseDate: { type: Date, required: true },

    /*
      NEW       = created, waiting for admin decision (no accounting entry)
      APPROVED  = approved by admin, journal posted
      REJECTED  = rejected by admin (no accounting entry)
      CANCELLED = withdrawn before approval
    */
    status: {
      type: String,
      enum: ["NEW", "APPROVED", "REJECTED", "CANCELLED"],
      default: "NEW",
      required: true,
      index: true,
    },

    /*
      PAID    = paid now from a cash / bank ledger
      PAYABLE = pay later, credited to the supplier ledger
    */
    paymentMode: {
      type: String,
      enum: ["PAID", "PAYABLE"],
      required: true,
    },

    paymentMethod: {
      type: String,
      enum: ["CASH", "BANK_TRANSFER", "UPI", "CHEQUE", "CARD", null],
      default: null,
    },

    paymentLedgerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "AccountingLedger",
      default: null,
    },
    paymentLedgerCode: { type: String, default: null },
    paymentLedgerName: { type: String, default: null },
    paymentLedgerType: {
      type: String,
      enum: ["CASH", "BANK", null],
      default: null,
    },

    supplierId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Supplier",
      default: null,
    },
    supplierCode: { type: String, default: null },
    supplierName: { type: String, default: null },
    supplierLedgerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "AccountingLedger",
      default: null,
    },

    payeeName: { type: String, default: null, trim: true, maxlength: 150 },
    referenceNumber: {
      type: String,
      default: null,
      trim: true,
      maxlength: 100,
    },

    currency: { type: String, enum: ["INR"], default: "INR", required: true },

    taxMode: { type: String, enum: ["NONE", "GST"], default: "NONE" },

    inputGstLedgerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "AccountingLedger",
      default: null,
    },
    tdsInput: {
      type: new mongoose.Schema(
        {
          natureId: mongoose.Schema.Types.ObjectId,
          deducteeType: String,
          pan: { type: String, default: null },
        },
        { _id: false },
      ),
      default: null,
    },
    tdsAmountPaise: {
      type: Number,
      default: 0,
      min: 0,
      validate: { validator: Number.isSafeInteger },
    },
    tds: { type: mongoose.Schema.Types.Mixed, default: null },
    lines: {
      type: [expenseLineSchema],
      required: true,
      validate: {
        validator: (lines) =>
          Array.isArray(lines) && lines.length >= 1 && lines.length <= 100,
        message: "An expense requires between 1 and 100 lines",
      },
    },

    taxableTotalPaise: { ...paise(), min: 1 },
    taxTotalPaise: paise(),
    totalAmountPaise: { ...paise(), min: 1 },

    notes: { type: String, default: null, trim: true, maxlength: 1000 },

    journalId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "AccountingJournal",
      default: null,
    },

    approvedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    approvedAt: { type: Date, default: null },

    rejectedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    rejectedAt: { type: Date, default: null },
    rejectionReason: {
      type: String,
      default: null,
      trim: true,
      maxlength: 500,
    },

    cancelledBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    cancelledAt: { type: Date, default: null },

    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    updatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
  },
  { timestamps: true, optimisticConcurrency: true },
);

expenseSchema.index({ tenantId: 1, expenseNumber: 1 }, { unique: true });
expenseSchema.index({ tenantId: 1, requestId: 1 }, { unique: true });
expenseSchema.index({ tenantId: 1, status: 1, expenseDate: -1 });
expenseSchema.index({ tenantId: 1, expenseDate: -1, createdAt: -1 });

expenseSchema.pre("validate", function () {
  let taxable = 0;
  let tax = 0;

  for (const line of this.lines || []) {
    if (line.amountPaise + line.taxPaise !== line.totalPaise) {
      this.invalidate("lines", "Line totals do not match amount plus tax");
      return;
    }
    taxable += line.amountPaise;
    tax += line.taxPaise;
  }

  if (
    this.taxableTotalPaise !== taxable ||
    this.taxTotalPaise !== tax ||
    this.totalAmountPaise !== taxable + tax
  ) {
    this.invalidate("lines", "Expense totals do not match its lines");
  }

  if (this.paymentMode === "PAID" && !this.paymentLedgerId) {
    this.invalidate(
      "paymentLedgerId",
      "A paid expense needs a cash or bank ledger",
    );
  }

  if (this.paymentMode === "PAYABLE" && !this.supplierId) {
    this.invalidate("supplierId", "A payable expense needs a supplier");
  }

  if (this.taxTotalPaise > 0 && !this.inputGstLedgerId) {
    this.invalidate("inputGstLedgerId", "Select the Input GST ledger");
  }
});

module.exports =
  mongoose.models.Expense || mongoose.model("Expense", expenseSchema);
