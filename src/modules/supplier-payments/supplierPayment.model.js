const mongoose = require("mongoose");

const positivePaise = () => ({
  type: Number,
  required: true,
  min: 1,
  validate: {
    validator: (value) =>
      Number.isSafeInteger(value) && value > 0,
    message: "Amount must be a positive safe integer in paise",
  },
});

const allocationSchema = new mongoose.Schema(
  {
    purchaseBillId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "PurchaseBill",
      required: true,
    },

    billNumber: {
      type: String,
      required: true,
      trim: true,
      uppercase: true,
    },

    supplierInvoiceNumber: {
      type: String,
      required: true,
      trim: true,
    },

    amountPaise: positivePaise(),
  },
  {
    _id: false,
  },
);

const supplierPaymentSchema = new mongoose.Schema(
  {
    tenantId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Tenant",
      required: true,
      index: true,
    },

    paymentNumber: {
      type: String,
      required: true,
      trim: true,
      uppercase: true,
    },

    /*
      Generated by the frontend once per payment attempt.
      The same key must be reused if that request is retried.
    */
    requestId: {
      type: String,
      required: true,
      trim: true,
      lowercase: true,
    },

    /*
      Calculated by the service from normalized request data.
      Used to reject reuse of requestId with different content.
    */
    requestHash: {
      type: String,
      required: true,
      select: false,
    },

    supplierId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Supplier",
      required: true,
    },

    supplierCode: {
      type: String,
      required: true,
      trim: true,
      uppercase: true,
    },

    supplierName: {
      type: String,
      required: true,
      trim: true,
    },

    supplierLedgerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "AccountingLedger",
      required: true,
    },

    paymentLedgerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "AccountingLedger",
      required: true,
    },

    paymentLedgerCode: {
      type: String,
      required: true,
      trim: true,
      uppercase: true,
    },

    paymentLedgerName: {
      type: String,
      required: true,
      trim: true,
    },

    paymentLedgerType: {
      type: String,
      enum: ["CASH", "BANK"],
      required: true,
    },

    paymentDate: {
      type: Date,
      required: true,
    },

    paymentMethod: {
      type: String,
      enum: [
        "CASH",
        "BANK_TRANSFER",
        "UPI",
        "CHEQUE",
        "CARD",
      ],
      required: true,
    },

    referenceNumber: {
      type: String,
      default: null,
      trim: true,
      maxlength: 100,
    },

    currency: {
      type: String,
      enum: ["INR"],
      default: "INR",
      required: true,
    },

    amountPaise: positivePaise(),

    allocations: {
      type: [allocationSchema],
      required: true,
      validate: {
        validator: (allocations) =>
          Array.isArray(allocations) &&
          allocations.length >= 1 &&
          allocations.length <= 200,
        message: "A payment requires between 1 and 200 bill allocations",
      },
    },

    /*
      Payments are posted immediately in version one.
      Cancellation is not exposed until reversal support exists.
    */
    status: {
      type: String,
      enum: ["POSTED"],
      default: "POSTED",
      required: true,
    },

    journalId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "AccountingJournal",
      required: true,
    },

    postedAt: {
      type: Date,
      required: true,
    },

    postedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    notes: {
      type: String,
      default: null,
      trim: true,
      maxlength: 1000,
    },

    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    updatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
  },
  {
    timestamps: true,
    optimisticConcurrency: true,
  },
);

supplierPaymentSchema.index(
  {
    tenantId: 1,
    paymentNumber: 1,
  },
  {
    unique: true,
  },
);

supplierPaymentSchema.index(
  {
    tenantId: 1,
    requestId: 1,
  },
  {
    unique: true,
  },
);

supplierPaymentSchema.index({
  tenantId: 1,
  paymentDate: -1,
  createdAt: -1,
});

supplierPaymentSchema.index({
  tenantId: 1,
  supplierId: 1,
  paymentDate: -1,
});

supplierPaymentSchema.index({
  tenantId: 1,
  "allocations.purchaseBillId": 1,
});

supplierPaymentSchema.pre("validate", function () {
  const allocations = this.allocations || [];

  let allocatedPaise = 0;
  const billIds = new Set();

  for (const allocation of allocations) {
    const billId = String(allocation.purchaseBillId);

    if (billIds.has(billId)) {
      this.invalidate(
        "allocations",
        "A bill can appear only once in a payment",
      );
      return;
    }

    billIds.add(billId);

    if (
      !Number.isSafeInteger(allocation.amountPaise) ||
      allocation.amountPaise <= 0
    ) {
      this.invalidate(
        "allocations",
        "Each allocation must be a positive integer in paise",
      );
      return;
    }

    allocatedPaise += allocation.amountPaise;

    if (!Number.isSafeInteger(allocatedPaise)) {
      this.invalidate(
        "allocations",
        "Allocated amount exceeds the supported range",
      );
      return;
    }
  }

  if (allocatedPaise !== this.amountPaise) {
    this.invalidate(
      "allocations",
      "Allocated amounts must equal the payment amount",
    );
  }

  if (
    this.paymentMethod === "CASH" &&
    this.paymentLedgerType !== "CASH"
  ) {
    this.invalidate(
      "paymentLedgerType",
      "Cash payments must use a CASH ledger",
    );
  }

  if (
    this.paymentMethod !== "CASH" &&
    this.paymentLedgerType !== "BANK"
  ) {
    this.invalidate(
      "paymentLedgerType",
      "Non-cash payments must use a BANK ledger",
    );
  }
});

module.exports =
  mongoose.models.SupplierPayment ||
  mongoose.model("SupplierPayment", supplierPaymentSchema);